export type MessageKey = keyof typeof en;

/**
 * The school's words for the things setup is about (D-114): Wing, Course, Level, Section (of a class) and Exam unless the
 * school renamed them. The config provider sets them once the school's configuration is known; until then, and in
 * tests that supply no school, they are the built-in defaults (the same as the API's `TERM_DEFAULTS`).
 */
export const DEFAULT_SCHOOL_WORDS = { section: "Wing", programme: "Course", level: "Level", classSection: "Section", terminal: "Exam" } as const;
export type SchoolWords = Record<keyof typeof DEFAULT_SCHOOL_WORDS, string>;
let schoolWords: SchoolWords = { ...DEFAULT_SCHOOL_WORDS };
export function setSchoolWords(words: Partial<SchoolWords>): void {
  schoolWords = { ...DEFAULT_SCHOOL_WORDS, ...Object.fromEntries(Object.entries(words).filter(([, v]) => typeof v === "string" && v !== "")) };
}

/**
 * The text for a key, with `{name}`-style values filled in. The school's words fill `{section}`, `{programme}`,
 * `{level}`, `{classSection}` and `{terminal}` when the caller does not pass them, so a raw "{programme}" never shows.
 */
export function t(key: MessageKey, values?: Record<string, string | number>): string {
  const text: string = en[key];
  if (!text.includes("{")) return text;
  const all: Record<string, string | number> = { ...schoolWords, ...values };
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in all ? String(all[name]) : whole));
}
